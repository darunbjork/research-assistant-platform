// backend/src/types/websocket.types.ts
// All WebSocket message types for the streaming agent protocol.
//
// PROTOCOL DESIGN:
// Every message is a typed JSON object with a "type" discriminant.
// This makes it easy to switch on the type on both sides.
//
// MESSAGE FLOW FOR ONE AGENT SESSION:
//   CLIENT → SERVER: { type: "start", query, sessionId }
//   SERVER → CLIENT: { type: "connected", sessionId }
//   SERVER → CLIENT: { type: "status", status: "thinking" }
//   SERVER → CLIENT: { type: "status", status: "searching" }
//   SERVER → CLIENT: { type: "step", step: { ... } }
//   SERVER → CLIENT: { type: "quality", score: 0.45, shouldRetry: true }
//   SERVER → CLIENT: { type: "status", status: "generating" }
//   SERVER → CLIENT: { type: "complete", result: { ... } }
//   SERVER → CLIENT: { type: "error", message: "..." }   (on failure)
//
// VOICE EXTENSION (Day 1 types — additive, no existing message changed):
//   CLIENT → SERVER: { type: "voice_start", sessionId }
//   CLIENT → SERVER: { type: "barge_in", sessionId }   (stop speaking)
//   CLIENT → SERVER: { type: "voice_end", sessionId }   (utterance over)
//   CLIENT → SERVER: binary audio_chunk (PCM16 LE, 16 kHz mono, ≤4096 B)
//   SERVER → CLIENT: { type: "transcript_interim", sessionId, text }
//   SERVER → CLIENT: { type: "transcript_final", sessionId, text, latencyMs }
//   SERVER → CLIENT: { type: "voice_summary", sessionId, text }
//   SERVER → CLIENT: binary tts_chunk (4-byte BE uint32 sequence + audio)
//   SERVER → CLIENT: { type: "tts_done", sessionId }
//   SERVER → CLIENT: { type: "voice_error", sessionId, code, message }
// Binary frames are routed on the `isBinary` flag BEFORE this JSON parser
// (Day 3), so they never reach parseClientMessage.

import type { AgentStatus, AgentStep, AgentResult } from "./agent.types"
import type { VoiceErrorCode } from "./voice.types"

// ── Messages the CLIENT sends to the SERVER ───────────────────────────────

export type ClientMessage =
  | StartAgentMessage
  | PingMessage
  | AuthMessage
  | VoiceStartMessage
  | BargeInMessage
  | VoiceEndMessage

export interface StartAgentMessage {
  type: "start"
  query: string
  sessionId: string // generated by the client
}

export interface PingMessage {
  type: "ping"
}

export interface AuthMessage {
  type: "auth"
  token: string
}

// ── Voice layer: CLIENT → SERVER control messages (Day 1) ─────────────────

export interface VoiceStartMessage {
  type: "voice_start"
  sessionId: string
}

export interface BargeInMessage {
  type: "barge_in"
  sessionId: string
}

export interface VoiceEndMessage {
  type: "voice_end"
  sessionId: string
}

// ── Messages the SERVER sends to the CLIENT ───────────────────────────────

export type ServerMessage =
  | ConnectedMessage
  | AuthConfirmedMessage
  | AgentStatusMessage
  | AgentStepMessage
  | QualityCheckMessage
  | AgentCompleteMessage
  | AgentErrorMessage
  | PongMessage
  | TranscriptInterimMessage
  | TranscriptFinalMessage
  | VoiceSummaryMessage
  | TtsDoneMessage
  | VoiceErrorMessage

export interface ConnectedMessage {
  type: "connected"
  sessionId: string
  message: string
}

export interface AuthConfirmedMessage {
  type: "auth_confirmed"
  userId: string
}

export interface AgentStatusMessage {
  type: "status"
  status: AgentStatus
  sessionId: string
  message: string // human-readable description of current stage
}

export interface AgentStepMessage {
  type: "step"
  sessionId: string
  step: AgentStep
}

export interface QualityCheckMessage {
  type: "quality"
  sessionId: string
  score: number // 0-1 overall quality score
  shouldRetry: boolean
  retryReason?: string
  suggestedQuery?: string
}

export interface AgentCompleteMessage {
  type: "complete"
  sessionId: string
  result: AgentResult
}

export interface AgentErrorMessage {
  type: "error"
  sessionId: string
  message: string
  code?: AgentErrorCode
}

/**
 * Machine-readable error codes sent with AgentErrorMessage.
 * Adding a code here does not change the message shape — `code` stays an
 * optional string field on the wire.
 */
export type AgentErrorCode =
  | "INVALID_MESSAGE"
  | "AUTH_FAILED"
  | "NOT_AUTHENTICATED"
  | "SESSION_BUSY"
  | "INVALID_QUERY"
  | "RATE_LIMITED"
  | "CAPACITY_REACHED"
  | "TOKEN_EXPIRED"
  | "REASONING_ERROR"
  | "AGENT_ERROR"

export interface PongMessage {
  type: "pong"
}

// ── Voice layer: SERVER → CLIENT messages (Day 1) ─────────────────────────

export interface TranscriptInterimMessage {
  type: "transcript_interim"
  sessionId: string
  text: string
}

export interface TranscriptFinalMessage {
  type: "transcript_final"
  sessionId: string
  text: string
  /** voice_start → final transcript available (browser clock, ms). */
  latencyMs: number
}

export interface VoiceSummaryMessage {
  type: "voice_summary"
  sessionId: string
  text: string
}

export interface TtsDoneMessage {
  type: "tts_done"
  sessionId: string
}

export interface VoiceErrorMessage {
  type: "voice_error"
  sessionId: string
  code: VoiceErrorCode
  message: string
}

// ── Helper: type-safe message serialiser ─────────────────────────────────
export function toJson(message: ServerMessage): string {
  return JSON.stringify(message)
}

// ── Helper: type-safe message parser ─────────────────────────────────────
export function parseClientMessage(raw: string): ClientMessage | null {
  try {
    const parsed = JSON.parse(raw) as { type?: unknown }

    if (typeof parsed.type !== "string") return null

    switch (parsed.type) {
      case "start":
      case "ping":
      case "auth":
      case "voice_start":
      case "barge_in":
      case "voice_end":
        return parsed as ClientMessage
      default:
        return null
    }
  } catch {
    return null
  }
}
